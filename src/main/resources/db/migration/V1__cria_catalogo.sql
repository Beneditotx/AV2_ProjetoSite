CREATE TABLE categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(40) NOT NULL UNIQUE,
    nome VARCHAR(80) NOT NULL
);

CREATE TABLE itens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    icone VARCHAR(12) NOT NULL,
    descricao VARCHAR(500) NOT NULL,
    receita VARCHAR(500) NOT NULL,
    localizacao VARCHAR(300) NOT NULL,
    desbloqueio VARCHAR(300) NOT NULL,
    categoria_id BIGINT NOT NULL,
    CONSTRAINT fk_itens_categoria FOREIGN KEY (categoria_id) REFERENCES categorias(id),
    CONSTRAINT uq_item_nome_categoria UNIQUE (nome, categoria_id)
);
